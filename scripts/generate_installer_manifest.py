#!/usr/bin/env python3
"""Build-time only: embed supported file identities, never original asset bytes."""
import hashlib,json,zipfile
from pathlib import Path
R=Path(__file__).resolve().parents[1]
m=json.loads((R/'docs/evidence/patched-v12.json').read_text())
lines=['// Generated by scripts/generate_installer_manifest.py; identities only.', 'struct Asset { const char *path, *sha; unsigned long long size; };','static const Asset payload_assets[] = {']
for i in m['files']:
 lines.append('{'+json.dumps(i['path'])+','+json.dumps(i['sha256'])+','+str(i['size'])+'},')
lines+=['};','static const Asset menu_assets[] = {']
with zipfile.ZipFile(R/'build/active/data/mainui.pak') as z:
 for i in z.infolist():
  if i.is_dir():continue
  parts=i.filename.split('/');parts[0]={'textures':'Textures','sound':'Sound','levels':'Levels'}[parts[0].lower()]
  b=z.read(i);lines.append('{'+json.dumps('data/'+'/'.join(parts))+','+json.dumps(hashlib.sha256(b).hexdigest())+','+str(len(b))+'},')
lines+=['};']
(R/'launcher/install_manifest.h').write_text('\n'.join(lines)+'\n')
